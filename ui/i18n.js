let language = "en";

const PATTERNS = [
  [/^The folder cannot be made: (.+)$/, "フォルダを作成できません: {1}"],
  [/^Export failed: (.+)$/, "エクスポートに失敗しました: {1}"],
  [/^Delete failed: (.+)$/, "削除に失敗しました: {1}"],
];

function pattern(text) {
  for (const [re, ja] of PATTERNS) {
    const m = re.exec(text);
    if (m) return ja.replace(/\{(\d)\}/g, (x, i) => JA[m[+i]] || m[+i]);
  }
  return null;
}

function t(text, vars) {
  const out = (language === "ja" && (JA[text] || pattern(text))) || text;
  return vars ? out.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : out;
}

function setLanguage(lang) {
  language = lang;
  document.documentElement.lang = lang;
  for (const e of document.querySelectorAll("[data-t]")) e.textContent = t(e.dataset.t);
  for (const e of document.querySelectorAll("[data-t-title]")) e.title = t(e.dataset.tTitle);
  for (const e of document.querySelectorAll("[data-t-placeholder]")) e.placeholder = t(e.dataset.tPlaceholder);
  for (const e of document.querySelectorAll("[data-t-label]")) e.setAttribute("aria-label", t(e.dataset.tLabel));
}
